impl SeatHandler for WaylandState {
    fn seat_state(&mut self) -> &mut SeatState {
        &mut self.seat_state
    }

    fn new_seat(&mut self, _conn: &Connection, _qh: &QueueHandle<Self>, _seat: wl_seat::WlSeat) {}

    fn new_capability(
        &mut self,
        _conn: &Connection,
        qh: &QueueHandle<Self>,
        seat: wl_seat::WlSeat,
        capability: Capability,
    ) {
        match capability {
            Capability::Keyboard if self.keyboard.is_none() => {
                let repeat = Box::new(
                    |state: &mut WaylandState, _kb: &wl_keyboard::WlKeyboard, event: KeyEvent| {
                        state.key_pressed(event);
                    },
                );
                if let Ok(kb) = self.seat_state.get_keyboard_with_repeat(
                    qh,
                    &seat,
                    None,
                    self.loop_handle.clone(),
                    repeat,
                ) {
                    self.keyboard = Some(kb);
                }
            }
            Capability::Pointer if self.pointer.is_none() => {
                if let Ok(p) = self.seat_state.get_pointer(qh, &seat) {
                    self.pointer = Some(p);
                }
            }
            _ => {}
        }
    }

    fn remove_capability(
        &mut self,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
        _seat: wl_seat::WlSeat,
        _capability: Capability,
    ) {
    }

    fn remove_seat(&mut self, _conn: &Connection, _qh: &QueueHandle<Self>, _seat: wl_seat::WlSeat) {
    }
}

impl KeyboardHandler for WaylandState {
    fn enter(
        &mut self,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
        _keyboard: &wl_keyboard::WlKeyboard,
        surface: &wl_surface::WlSurface,
        _serial: u32,
        _raw: &[u32],
        _keysyms: &[Keysym],
    ) {
        if let Some(i) = self.record_for_surface(surface) {
            let id = self.windows[i].data.id;
            self.keyboard_focus = Some(id);
            self.windows[i].data.state.update(|s| s.focused = true);
            self.push(id, WindowEvent::Focused(true));
        }
    }

    fn leave(
        &mut self,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
        _keyboard: &wl_keyboard::WlKeyboard,
        surface: &wl_surface::WlSurface,
        _serial: u32,
    ) {
        if let Some(i) = self.record_for_surface(surface) {
            let id = self.windows[i].data.id;
            self.keyboard_focus = None;
            // Keys released while unfocused send no events, so the modifiers are cleared here.
            if self.modifiers != ModifiersState::empty() {
                let cleared = ModifiersState::empty();
                self.modifiers = cleared;
                self.push(id, WindowEvent::ModifiersChanged(cleared));
            }
            self.windows[i].data.state.update(|s| s.focused = false);
            self.push(id, WindowEvent::Focused(false));
        }
    }

    fn press_key(
        &mut self,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
        _keyboard: &wl_keyboard::WlKeyboard,
        _serial: u32,
        event: KeyEvent,
    ) {
        self.key_pressed(event);
    }

    fn release_key(
        &mut self,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
        _keyboard: &wl_keyboard::WlKeyboard,
        _serial: u32,
        event: KeyEvent,
    ) {
        let Some(id) = self.keyboard_focus else {
            return;
        };
        let code = key_from_xkb(event.raw_code);
        self.push(
            id,
            WindowEvent::KeyboardInput {
                state: ElementState::Released,
                key_code: code,
                physical_key: PhysicalKey::Code(code),
            },
        );
    }

    fn update_modifiers(
        &mut self,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
        _keyboard: &wl_keyboard::WlKeyboard,
        _serial: u32,
        modifiers: Modifiers,
        _layout: u32,
    ) {
        let mods = ModifiersState::new(
            modifiers.shift,
            modifiers.ctrl,
            modifiers.alt,
            modifiers.logo,
        );
        if mods != self.modifiers {
            self.modifiers = mods;
            if let Some(id) = self.keyboard_focus {
                self.push(id, WindowEvent::ModifiersChanged(mods));
            }
        }
    }
}

impl PointerHandler for WaylandState {
    fn pointer_frame(
        &mut self,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
        _pointer: &wl_pointer::WlPointer,
        events: &[PointerEvent],
    ) {
        for ev in events {
            let Some(i) = self.record_for_surface(&ev.surface) else {
                continue;
            };
            let id = self.windows[i].data.id;
            let scale = f64::from(self.windows[i].scale);
            let (x, y) = ev.position;
            match ev.kind {
                PointerEventKind::Enter { .. } => {
                    self.pointer_over = Some((id, x, y));
                    self.push(
                        id,
                        WindowEvent::CursorMoved {
                            position: PhysicalPosition::new(x * scale, y * scale),
                            pressure: 0.0,
                        },
                    );
                }
                PointerEventKind::Leave { .. } => {
                    self.pointer_over = None;
                    self.push(id, WindowEvent::CursorLeft);
                }
                PointerEventKind::Motion { .. } => {
                    self.pointer_over = Some((id, x, y));
                    self.push(
                        id,
                        WindowEvent::CursorMoved {
                            position: PhysicalPosition::new(x * scale, y * scale),
                            pressure: 0.0,
                        },
                    );
                }
                PointerEventKind::Press { button, .. } => {
                    self.push(
                        id,
                        WindowEvent::MouseInput {
                            state: ElementState::Pressed,
                            button: mouse_button(button),
                        },
                    );
                }
                PointerEventKind::Release { button, .. } => {
                    self.push(
                        id,
                        WindowEvent::MouseInput {
                            state: ElementState::Released,
                            button: mouse_button(button),
                        },
                    );
                }
                PointerEventKind::Axis {
                    horizontal,
                    vertical,
                    ..
                } => {
                    // Wayland reports scrolling away from the user as positive; tpt-window
                    // reports wheel-up as positive, so the sign is flipped.
                    let delta = if vertical.discrete != 0 || horizontal.discrete != 0 {
                        MouseScrollDelta::LineDelta {
                            x: -(horizontal.discrete as f32),
                            y: -(vertical.discrete as f32),
                        }
                    } else {
                        MouseScrollDelta::PixelDelta {
                            x: -horizontal.absolute * scale,
                            y: -vertical.absolute * scale,
                        }
                    };
                    self.push(
                        id,
                        WindowEvent::MouseWheel {
                            delta,
                            phase: TouchPhase::Moved,
                        },
                    );
                }
            }
        }
    }
}

impl WindowHandler for WaylandState {
    fn request_close(&mut self, _conn: &Connection, _qh: &QueueHandle<Self>, window: &Window) {
        if let Some(i) = self
            .windows
            .iter()
            .position(|r| r.window.wl_surface() == window.wl_surface())
        {
            let id = self.windows[i].data.id;
            self.push(id, WindowEvent::CloseRequested);
        }
    }

    fn configure(
        &mut self,
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
        window: &Window,
        configure: WindowConfigure,
        _serial: u32,
    ) {
        let Some(i) = self
            .windows
            .iter()
            .position(|r| r.window.wl_surface() == window.wl_surface())
        else {
            return;
        };
        let (w, h) = configure.new_size;
        let (cur_w, cur_h) = {
            let rec = &self.windows[i];
            (rec.size.width, rec.size.height)
        };
        let logical = (
            w.map_or(cur_w / self.windows[i].scale as u32, NonZeroU32::get),
            h.map_or(cur_h / self.windows[i].scale as u32, NonZeroU32::get),
        );
        let physical = WaylandState::physical(self.windows[i].scale, logical);
        let first = !self.windows[i].configured;
        self.windows[i].configured = true;
        if first || physical != self.windows[i].size {
            let id = self.windows[i].data.id;
            self.windows[i].size = physical;
            self.windows[i].data.state.update(|s| s.size = physical);
            self.push(id, WindowEvent::Resized(physical));
        }
    }
}

